/** Перевод ответов анкеты в оценки критериев 1-5. Массовость считает ИИ по похожим обращениям. */
export function priorityFromAnswers(a: Answers, mass: number): PriorityInput {
  const threatByHealth = [1, 2, 3, 4, 5][a.health] ?? 1
  const threat = Math.max(threatByHealth, a.change === 4 ? 4 : 1)
  let vuln = a.group > 0 ? 3 : 1
  if (a.location === 3 || a.location === 1 || a.location === 2) vuln += 1
  if (a.comm > 0) vuln += 1
  if (a.group === 1 || a.group === 2) vuln += 1
  const rights = [1, 2, 3, 4, 5][a.change] ?? 1
  const urgency = [5, 4, 3, 2, 1][a.when] ?? 1
  const people = [1, 1, 1, 2, 3, 4, 5][a.victims] ?? 1
  const repeat = [1, 2, 3, 4, 5][a.prior] ?? 1
  return { threat, vuln: Math.min(5, vuln), rights, urgency, people, mass, repeat }
}

