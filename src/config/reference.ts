export type PClass = 'Критический' | 'Высокий' | 'Средний' | 'Низкий'
export const PCLASSES: PClass[] = ['Критический', 'Высокий', 'Средний', 'Низкий']

export function score(p: PriorityInput): number {
  let s = 0
  for (const c of CRITERIA) s += c.w * p[c.key]
  // угроза 5 поднимает балл до 85, угроза 4 до 75
  if (p.threat === 5) s = Math.max(s, 85)
  else if (p.threat === 4) s = Math.max(s, 75)
  return s
}
export function pclass(s: number): PClass {
  if (s >= 80) return 'Критический'
  if (s >= 60) return 'Высокий'
  if (s >= 35) return 'Средний'
  return 'Низкий'
}
export const isSystemic = (p: PriorityInput) => p.mass >= 4 && p.rights >= 3

